const fs = require("node:fs");
const vm = require("node:vm");
const files = ["eng-words.js", "eng-cloze-basic.js", "eng-cloze-advanced.js", "eng-cloze-real.js", "eng-reading-basic.js", "eng-reading-advanced.js", "eng-reading-exam.js", "eng-listening-basic.js", "eng-listening-advanced.js", "eng-listening-exam.js", "eng-translation.js"];
const context = { window: {} };
files.forEach((file) => vm.runInNewContext(fs.readFileSync(file, "utf8"), context, { filename: file }));
const dict = {};
for (const day of context.window.ENG_WORD_DAYS || []) for (const item of day.words || []) dict[item.w.toLowerCase()] = { pos: item.pos || "", meaning: item.meaning || "", phon: item.phon || "" };
const texts = [];
function collect(value, key) {
  if (typeof value === "string") { if (/text|title|prompt|passage|question|options|reference|chinese|en|topic|source|analysis/i.test(key || "")) texts.push(value); }
  else if (Array.isArray(value)) value.forEach((item) => collect(item, key));
  else if (value && typeof value === "object") Object.keys(value).forEach((child) => collect(value[child], child));
}
Object.keys(context.window).forEach((name) => { if (name !== "ENG_WORD_DAYS" && name !== "ENG_PHRASE_DAYS") collect(context.window[name], name); });
const words = new Set();
for (const text of texts) for (const match of text.matchAll(/[A-Za-z]+(?:['’][A-Za-z]+)*/g)) {
  const word = match[0].replace(/[’]/g, "'").toLowerCase();
  if (word.length > 1) words.add(word);
}
const answerPos = {};
for (const name of Object.keys(context.window).filter((key) => key.startsWith("ENG_CLOZE_"))) for (const ep of context.window[name] || []) for (const blank of ep.blanks || []) if (blank.word && blank.pos) answerPos[blank.word.toLowerCase()] = blank.pos;
const exact = { supersensitive: { pos: "adj.", meaning: "对……过度敏感的；高度敏感的" } };
const irregular = { people: "person", children: "child", men: "man", women: "woman", teeth: "tooth", feet: "foot", studies: "study", analyses: "analysis", data: "datum" };
function bases(word) {
  const list = [word];
  if (irregular[word]) list.push(irregular[word]);
  if (/ies$/.test(word)) list.push(word.slice(0, -3) + "y");
  if (/ied$/.test(word)) list.push(word.slice(0, -3) + "y");
  if (/ing$/.test(word)) { const stem = word.slice(0, -3); list.push(stem, stem + "e"); if (/(.)\\1$/.test(stem)) list.push(stem.slice(0, -1)); }
  if (/ed$/.test(word)) { const stem = word.slice(0, -2); list.push(stem, stem + "e"); }
  if (/es$/.test(word)) list.push(word.slice(0, -2), word.slice(0, -1));
  if (/s$/.test(word)) list.push(word.slice(0, -1));
  if (/er$/.test(word)) list.push(word.slice(0, -2));
  if (/est$/.test(word)) list.push(word.slice(0, -3));
  return [...new Set(list)];
}
function posOf(word) {
  if (/ly$/.test(word)) return "adv.";
  if (/(ous|ful|less|ive|able|ible|al|ic|ish|ary|ent|ant|ed|ing)$/.test(word)) return "adj.";
  if (/(tion|sion|ment|ness|ity|ance|ence|ship|ism|ist|er|or|age|ure)$/.test(word)) return "n.";
  if (/(ize|ise|fy|en)$/.test(word)) return "v.";
  return "词性待查";
}
function meaningOf(word) {
  if (/ly$/.test(word)) return "以……方式；……地";
  if (/(tion|sion|ment|ness|ity|ance|ence|ship|ism|age|ure)$/.test(word)) return "行为、状态或结果";
  if (/(ous|ful|less|ive|able|ible|al|ic|ish|ary|ent|ant|ed|ing)$/.test(word)) return "具有……性质的；相关的";
  if (/(ize|ise|fy|en)$/.test(word)) return "使……；变得……";
  return "英语词汇（请通过有道词典核对具体释义）";
}
for (const word of words) {
  if (dict[word]) continue;
  if (exact[word]) { dict[word] = { ...exact[word], phon: "" }; continue; }
  const base = bases(word).find((candidate) => dict[candidate]);
  dict[word] = base ? { ...dict[base], pos: answerPos[word] || dict[base].pos || "", phon: "" } : { pos: answerPos[word] || posOf(word), meaning: meaningOf(word), phon: "" };
}
fs.writeFileSync("eng-dict.js", "/* Generated by build-eng-dict.js from English learning data. */\nwindow.ENG_CORPUS_DICT = " + JSON.stringify(dict) + ";\n", "utf8");
console.log("Wrote " + Object.keys(dict).length + " entries from " + words.size + " unique corpus words.");
